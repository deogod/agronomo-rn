import { useMutation } from '@tanstack/react-query';
import { useRef, useState } from 'react';
import {
  KeyboardAvoidingView,
  Platform,
  ScrollView,
  StyleSheet,
  View,
  type TextInputInstance,
} from 'react-native';

import { useAuthenticationLogin } from '@/api/generated/endpoints/authentication/authentication';
import { signInWithGoogle } from '@/features/auth/google-sign-in';
import { signIn } from '@/features/auth/session-store';
import { AppText, Button, ErrorBanner, Screen, TextField, useTheme, type Theme } from '@/ui';

const EMAIL_PATTERN = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

function validate(email: string, password: string) {
  const trimmed = email.trim();
  return {
    email: !trimmed
      ? 'Informe o e-mail'
      : !EMAIL_PATTERN.test(trimmed)
        ? 'E-mail inválido'
        : undefined,
    password: !password.trim() ? 'Informe a senha' : undefined,
  };
}

/**
 * E-mail/password login (Flutter: LoginPage + LoginBloc).
 * On success the tokens go to the session store; the root layout guard then
 * swaps this screen for the app, so there is no navigation call here.
 */
export default function Login() {
  const theme = useTheme();
  const styles = createStyles(theme);
  const passwordRef = useRef<TextInputInstance>(null);

  const [email, setEmail] = useState('');
  const [password, setPassword] = useState('');
  // Field errors show only after the first submit attempt.
  const [submitted, setSubmitted] = useState(false);

  const login = useAuthenticationLogin({
    mutation: {
      // Returning the promise keeps isPending true until the session is saved.
      onSuccess: (response) => signIn(response.data),
    },
  });

  // Not generated by Orval: three hops (Google, Firebase, API), see google-sign-in.ts.
  const google = useMutation({
    mutationFn: signInWithGoogle,
    // null = the user closed the Google sheet: nothing to do.
    onSuccess: (tokens) => (tokens ? signIn(tokens) : undefined),
  });

  // Derived during render: no effect and no extra state for the errors.
  const errors = validate(email, password);
  const busy = login.isPending || google.isPending;
  const error = login.error ?? google.error;

  function submit() {
    setSubmitted(true);
    if (errors.email || errors.password || busy) return;
    login.mutate({
      // Same normalization as the Flutter app (accounts were created that way).
      data: { email: email.trim().toLowerCase(), password: password.trim() },
    });
  }

  function onEdit(setter: (value: string) => void) {
    return (value: string) => {
      setter(value);
      // Typing again hides the previous API error.
      if (login.isError) login.reset();
      if (google.isError) google.reset();
    };
  }

  return (
    <Screen>
      <KeyboardAvoidingView
        style={styles.flex}
        behavior={Platform.OS === 'ios' ? 'padding' : undefined}
      >
        <ScrollView contentContainerStyle={styles.content} keyboardShouldPersistTaps="handled">
          <View style={styles.header}>
            <AppText variant="title" tone="primary">
              Meu Agrônomo
            </AppText>
            <AppText tone="muted">Faça login para começar</AppText>
          </View>

          <TextField
            label="E-mail"
            value={email}
            onChangeText={onEdit(setEmail)}
            error={submitted ? errors.email : undefined}
            placeholder="voce@exemplo.com"
            keyboardType="email-address"
            autoCapitalize="none"
            autoCorrect={false}
            autoComplete="email"
            textContentType="emailAddress"
            returnKeyType="next"
            submitBehavior="submit"
            onSubmitEditing={() => passwordRef.current?.focus()}
            editable={!busy}
          />
          <TextField
            ref={passwordRef}
            label="Senha"
            value={password}
            onChangeText={onEdit(setPassword)}
            error={submitted ? errors.password : undefined}
            placeholder="Digite sua senha"
            secureTextEntry
            autoComplete="current-password"
            textContentType="password"
            returnKeyType="go"
            onSubmitEditing={submit}
            editable={!busy}
          />

          {error ? <ErrorBanner message={error.message} /> : null}

          <Button title="Entrar" onPress={submit} loading={login.isPending} disabled={busy} />

          <View style={styles.divider}>
            <View style={styles.line} />
            <AppText tone="muted">ou</AppText>
            <View style={styles.line} />
          </View>

          <Button
            title="Entrar com Google"
            variant="outlined"
            onPress={() => {
              login.reset();
              google.mutate();
            }}
            loading={google.isPending}
            disabled={busy}
          />
        </ScrollView>
      </KeyboardAvoidingView>
    </Screen>
  );
}

const createStyles = (theme: Theme) =>
  StyleSheet.create({
    flex: {
      flex: 1,
    },
    content: {
      flexGrow: 1,
      justifyContent: 'center',
      gap: theme.spacing.md,
      paddingVertical: theme.spacing.xl,
    },
    header: {
      gap: theme.spacing.xs,
      marginBottom: theme.spacing.lg,
    },
    divider: {
      flexDirection: 'row',
      alignItems: 'center',
      gap: theme.spacing.sm,
    },
    line: {
      flex: 1,
      height: StyleSheet.hairlineWidth,
      backgroundColor: theme.colors.outlineVariant,
    },
  });
